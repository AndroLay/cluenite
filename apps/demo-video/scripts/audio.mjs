// Builds the demo audio: Kokoro narration (through the hyperframes CLI) and a
// light background bed synthesized locally with ffmpeg. Nothing here is licensed
// media. Run from apps/demo-video with: npm run audio
// If hyperframes picks a Python without kokoro-onnx, set HYPERFRAMES_PYTHON to the
// interpreter that has it (the CLI reads that variable and inherits it from this process).
import {spawnSync} from 'node:child_process';
import {mkdirSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VOICE = 'bm_george'; // Kokoro British male. List voices: npx hyperframes tts --list
const BED_SECONDS = 175; // Must match TOTAL_SECONDS in src/timeline.ts

// One narration line per segment. atSec is the offset from the segment start.
// Text matches the voice-over lines in docs/demo/DEMO_VIDEO_PLAN.md (Section 3).
const LINES = [
  {id: 'S1', segment: 'S1', atSec: 0.6, text: 'One minute of downtime becomes a shared mystery.'},
  {id: 'S2', segment: 'S2', atSec: 0.6, text: 'Chat finds evidence directly in Twitch.'},
  {id: 'S3', segment: 'S3', atSec: 0.6, text: "It's not votes; the evidence changes game state."},
  {id: 'S4', segment: 'S4', atSec: 0.6, text: 'Same engine, deeper investigation.'},
  {id: 'S5', segment: 'S5', atSec: 0.6, text: 'Wrong theories are tested, not punished.'},
  {id: 'S6', segment: 'S6', atSec: 0.6, text: 'Layouts hold at phone and desktop widths.'},
  {id: 'S7', segment: 'S7', atSec: 0.6, text: 'Built using Codex, deterministic proof tests and EventSub.'},
  {id: 'S8', segment: 'S8', atSec: 0.6, text: 'Every clue brings us together.'},
];

const run = (command, args, options = {}) => {
  const result = spawnSync(command, args, {encoding: 'utf8', ...options});
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    throw new Error(`${command} failed (exit ${result.status}):\n${result.stderr || result.stdout}`);
  }
  return result.stdout;
};

const publicAudio = join(ROOT, 'public', 'audio', 'vo');
const generatedDir = join(ROOT, 'src', 'audio');
mkdirSync(publicAudio, {recursive: true});
mkdirSync(generatedDir, {recursive: true});

// 1. Narration: one WAV per line, then measure its real duration.
const narration = LINES.map((line) => {
  if (line.text.includes('"')) {
    throw new Error(`Narration text must not contain double quotes: ${line.id}`);
  }
  const file = `audio/vo/${line.id}.wav`;
  const outPath = join(ROOT, 'public', file);
  // shell: true is required so Windows resolves npx.cmd. Node does not quote args in shell
  // mode, so the whole command is one string. Text is quoted; paths contain no spaces.
  run(`npx -y hyperframes tts "${line.text}" --voice ${VOICE} --output "${outPath}"`, [], {
    shell: true,
  });
  const probed = run('ffprobe', [
    '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', outPath,
  ]);
  const durationSec = Number.parseFloat(probed.trim());
  if (!Number.isFinite(durationSec)) {
    throw new Error(`Could not read duration for ${file}: ${probed}`);
  }
  return {...line, file, durationSec: Math.round(durationSec * 100) / 100};
});

// 2. Generated TypeScript module read by src/audio/Narration.tsx.
const tsSource = [
  '// Generated by scripts/audio.mjs. Do not edit by hand; run `npm run audio`.',
  'export type NarrationLine = {',
  '  id: string;',
  '  segment: string;',
  '  atSec: number;',
  '  durationSec: number;',
  '  file: string;',
  '  text: string;',
  '};',
  '',
  'export const NARRATION: readonly NarrationLine[] = [',
  ...narration.map(
    (line) =>
      `  {id: ${JSON.stringify(line.id)}, segment: ${JSON.stringify(line.segment)}, ` +
      `atSec: ${line.atSec}, durationSec: ${line.durationSec}, ` +
      `file: ${JSON.stringify(line.file)}, text: ${JSON.stringify(line.text)}},`,
  ),
  '];',
  '',
].join('\n');
writeFileSync(join(generatedDir, 'narration.generated.ts'), tsSource, 'utf8');

// 3. Background bed: two quiet drone tones with slow tremolo, plus faint pink
// noise for texture. Mono, 64 kbps MP3, faded in and out.
const bedPath = join(ROOT, 'public', 'audio', 'bed.mp3');
const sine = (hz) => `sine=frequency=${hz}:duration=${BED_SECONDS}`;
run('ffmpeg', [
  '-y', '-hide_banner', '-loglevel', 'error',
  '-f', 'lavfi', '-i', sine(55),
  '-f', 'lavfi', '-i', sine(82.41),
  '-f', 'lavfi', '-i', sine(110),
  '-f', 'lavfi', '-i', `anoisesrc=color=pink:amplitude=0.5:duration=${BED_SECONDS}:sample_rate=44100`,
  '-filter_complex', [
    '[0:a][1:a][2:a]amix=inputs=3:normalize=0,tremolo=f=0.1:d=0.25,lowpass=f=500,volume=0.25[tone]',
    '[3:a]highpass=f=150,lowpass=f=2500,volume=0.05[hiss]',
    `[tone][hiss]amix=inputs=2:normalize=0,afade=t=in:st=0:d=4,afade=t=out:st=${BED_SECONDS - 5}:d=5[out]`,
  ].join(';'),
  '-map', '[out]', '-t', String(BED_SECONDS), '-ac', '1', '-ar', '44100',
  '-c:a', 'libmp3lame', '-b:a', '64k', bedPath,
]);

// 4. Summary.
for (const line of narration) {
  console.log(`${line.id}  ${line.durationSec.toFixed(2)}s  ${line.file}`);
}
console.log(`bed  ${BED_SECONDS}s  audio/bed.mp3  ${(statSync(bedPath).size / 1024).toFixed(0)} KB`);
